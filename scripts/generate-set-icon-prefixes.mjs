import { readFile, writeFile } from 'node:fs/promises';

const source = await readFile(new URL('../lib/esoSets.ts', import.meta.url), 'utf8');
const setNames = [...source.matchAll(/setName: "([^"]+)"/g)].map((match) => match[1]);
const slugify = (name) => name.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/['’]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const results = new Map();
const sources = new Map();
const failures = [];
let cursor = 0;

async function worker() {
  while (cursor < setNames.length) {
    const name = setNames[cursor++];
    const response = await fetch(`https://eso-hub.com/en/sets/${slugify(name)}`);
    const html = await response.text();
    const prefix = html.match(/https:\/\/eso-hub\.com\/storage\/icons\/gear_([^_]+)_/)?.[1];
    const source = html.match(/https:\/\/eso-hub\.com\/storage\/icons\/gear_[^"'\\ ]+\.(?:png|webp)/)?.[0];
    if (!response.ok || !prefix || !source) failures.push(`${name}: ${response.url}`);
    else {
      results.set(name, prefix);
      sources.set(name, source);
    }
  }
}

await Promise.all(Array.from({ length: 6 }, worker));
const entries = [...results.entries()].sort(([left], [right]) => left.localeCompare(right));
await writeFile(
  new URL('../lib/setIconPrefixes.ts', import.meta.url),
  `// Generated by scripts/generate-set-icon-prefixes.mjs. Do not hand-edit.\nexport const SET_ICON_PREFIXES: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\n\nexport const SET_ICON_SOURCES: Record<string, string> = ${JSON.stringify(Object.fromEntries([...sources.entries()].sort(([left], [right]) => left.localeCompare(right))), null, 2)};\n`,
);
process.stderr.write(`Resolved ${results.size}/${setNames.length} set icon prefixes.\n`);
if (failures.length) {
  process.stderr.write(`No direct page match for ${failures.length} set(s):\n${failures.join('\n')}\n`);
  process.exitCode = 1;
}
